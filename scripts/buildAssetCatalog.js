// Edit assetSources.json deliberately: unused/source art must never enter a release by directory scanning.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(__dirname, 'assetSources.json');
const CATALOG = path.join(ROOT, 'src/assets/AssetCatalog.ts');
const STAGING = path.join(ROOT, 'node_modules/.cache/asset-release');
const OBJECT_PREFIX = 'assets/v1/';
const json = value => JSON.stringify(value, null, 2) + '\n';

function buildCatalog(source = JSON.parse(fs.readFileSync(SOURCE, 'utf8')), root = ROOT) {
    const storage = source.storage;
    if (!storage || !['local', 'cloud'].includes(storage.mode)
        || typeof storage.envId !== 'string' || !/^[a-zA-Z0-9_-]+$/.test(storage.envId)
        || !/^jwr-assets-[a-zA-Z0-9_-]+$/.test(storage.cacheDirectory))
        throw Error('Invalid asset storage configuration');
    if (typeof source.cloudRoot !== 'string' || !/^cloud:\/\/[a-zA-Z0-9._-]+\/$/.test(source.cloudRoot))
        throw Error('cloudRoot must be a CloudBase file-ID root ending in /');
    if (!Array.isArray(source.assets) || !source.assets.length) throw Error('An explicit asset source list is required');

    const catalog = {}, contents = new Map(), uploads = [], seen = new Set();
    const realRoot = fs.realpathSync(root);
    const sources = source.assets.slice().sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
    for (const item of sources) {
        const logical = item.path;
        if (typeof logical !== 'string' || !logical || logical.includes('\\') || path.posix.isAbsolute(logical)
            || logical.split('/').some(part => !part || part === '.' || part === '..') || seen.has(logical))
            throw Error('Invalid or duplicate logical asset path: ' + logical);
        if (!['image', 'audio', 'binary'].includes(item.kind)) throw Error('Invalid asset kind: ' + logical);
        const extension = path.posix.extname(logical).toLowerCase();
        if (!/^\.[a-z0-9]{1,8}$/.test(extension)) throw Error('An asset requires a simple file extension: ' + logical);
        const file = fs.realpathSync(path.join(realRoot, logical));
        if (!file.startsWith(realRoot + path.sep) || !fs.statSync(file).isFile())
            throw Error('Asset must be a file inside the repository: ' + logical);
        const data = fs.readFileSync(file);
        if (!data.length) throw Error('Asset is empty: ' + logical);
        seen.add(logical);
        const sha256 = crypto.createHash('sha256').update(data).digest('hex');
        const md5 = crypto.createHash('md5').update(data).digest('hex');
        const objectKey = OBJECT_PREFIX + sha256 + extension;
        const entry = { fileID: source.cloudRoot + objectKey, sha256, md5, bytes: data.length, kind: item.kind };
        catalog[logical] = entry;
        contents.set(objectKey, data);
        uploads.push({ path: logical, objectKey, ...entry });
    }
    const normalizedStorage = { mode: storage.mode, envId: storage.envId, cacheDirectory: storage.cacheDirectory };
    const manifest = {
        schemaVersion: 1,
        storage: normalizedStorage,
        cloudRoot: source.cloudRoot,
        assetCount: uploads.length,
        uploadCount: contents.size,
        totalBytes: Array.from(contents.values()).reduce((sum, data) => sum + data.length, 0),
        assets: uploads,
    };
    const typescript = '// Generated by scripts/buildAssetCatalog.js from scripts/assetSources.json. Do not edit.\n'
        + '// Upload availability is not implied by this catalog; local mode remains active until release setup completes.\n'
        + 'export type AssetCatalogEntry = {\n'
        + "    fileID: string; sha256: string; md5: string; bytes: number; kind: 'image' | 'audio' | 'binary';\n"
        + '};\n\n'
        + 'export const ASSET_STORAGE = {\n'
        + `    mode: '${storage.mode}' as 'cloud' | 'local',\n`
        + `    envId: '${storage.envId}',\n`
        + `    cacheDirectory: '${storage.cacheDirectory}',\n`
        + '};\n\n'
        + 'export const ASSET_CATALOG: Record<string, AssetCatalogEntry> = ' + JSON.stringify(catalog, null, 2) + ';\n';
    return { catalog, manifest, typescript, contents };
}

function writeIfChanged(file, text) {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
}

function stageRelease(result, directory = STAGING) {
    // This directory is disposable build output. Recreate it to exclude stale objects from flat uploads.
    fs.rmSync(directory, { recursive: true, force: true });
    fs.mkdirSync(path.join(directory, OBJECT_PREFIX), { recursive: true });
    for (const [objectKey, data] of result.contents) fs.writeFileSync(path.join(directory, objectKey), data);
    fs.writeFileSync(path.join(directory, 'manifest.json'), json(result.manifest));
}

function run(args = process.argv.slice(2)) {
    if (args.some(arg => arg !== '--check') || args.length > 1)
        throw Error('Usage: node scripts/buildAssetCatalog.js [--check]');
    const result = buildCatalog();
    if (args.includes('--check')) {
        // Ignored staging output is intentionally not required on a clean checkout or in CI.
        if (!fs.existsSync(CATALOG) || fs.readFileSync(CATALOG, 'utf8') !== result.typescript)
            throw Error('AssetCatalog.ts is stale; run node scripts/buildAssetCatalog.js');
        console.log(`Asset catalog verified: ${result.manifest.assetCount} assets, ${result.manifest.totalBytes} bytes, mode=${result.manifest.storage.mode}.`);
        return result;
    }
    writeIfChanged(CATALOG, result.typescript);
    stageRelease(result);
    console.log(`Generated ${result.manifest.assetCount} assets (${result.manifest.totalBytes} bytes), mode=${result.manifest.storage.mode}.`);
    console.log('Upload files: node_modules/.cache/asset-release/assets/v1/');
    console.log('Manifest: node_modules/.cache/asset-release/manifest.json');
    return result;
}

if (require.main === module) {
    try { run(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { buildCatalog, stageRelease, run };
